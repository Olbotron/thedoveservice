DOVE BUDDIES SOCIAL GROUPS<br>
We recognise that not everyone who experiences a bereavement or loss needs specialist counselling to feel like themselves again and because of that, we offer social groups across North Staffordshire and Cheshire. Dove Buddies is a place to meet other people in a similar position to yourself and to create friendships. 
