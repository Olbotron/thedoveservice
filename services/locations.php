Bereavement<br>
ADULT BEREAVEMENT GROUPS<br>
Facilitated by trained counsellors, bereavement groups are therapeutic groups in which those present have the space to grieve, express their feelings and share their stories in a safe and confidential setting that is inclusive and non-judgemental. Exploring your loss as part of a group and sharing your experiences with others who are also grieving can help you find a way forward through your individual experience of bereavement.<br> 
