<h3>HOW WE CAN HELP YOUR ORGANISATION</h3>
At the Dove Service, we know that one of the biggest causes of problems for the staff in any organisation is bereavement, significant loss, and issues around life-changing/limiting illnesses, which results in stress, anxiety, and other mental health issues.  We strongly believe that spending time and money on employee well-being is a clear demonstration of an organisation’s duty of care to its employees.<br>
<br>
We understand that it can be difficult for employers to identify when an employee is experiencing feelings associated with bereavement and loss, and even harder to know how to support that person.  We want to ensure that managers, staff and volunteers are provided with training, supportand counselling, to facilitate their well-being.<br>
<br>
For practical information and resources on the importance of practising self-care while experiencing a bereavement follow the link to our self-care page.<br>
