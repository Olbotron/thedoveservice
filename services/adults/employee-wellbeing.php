<h2>EMERGENCY SUPPORT</h2>
The Dove Service also provides emergency support to businesses and organisations that may have experienced a sudden death in service.  We can provide a general group session or a drop-in service, giving staff at all levels in the organisation an opportunity to talk and share their feelings. We typically provide 2 counsellors to deliver support for a minimum of 2 hours. For further information on how we can help and our charges, please contact our team at our Head Office via telephone: 01782 914455 or email @Enquiries, we can react quickly to your needs.</h2> 
