EMPLOYEE WELLBEING SERVICES<br>
The Dove Service works in partnership with local employers across the region to provide counselling, awareness raising and training, to support our communities’ emotional health and wellbeing. We can also offer group support sessions for staff following an employee death or other traumatic incident.<br>
<br>
We understand that it can be difficult for employers to identify when an employee is experiencing feelings associated with bereavement and loss, and even harder to know how to support that person.  We want to ensure that managers, staff and volunteers are provided with training, support and counselling, which supports their well-being.<br>
