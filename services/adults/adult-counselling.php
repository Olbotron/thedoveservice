<h2>SELF-FUNDED COUNSELLING</h2>
We can provide self funded counselling to adults and children if you do not qualify for any of our free services including via NHS Staffordshire Talking Therapies or live outside of Staffordshire or East Cheshire.<br> 
<br>
Our self funded counselling means there is no waiting and fewer limits to the sessions you can receive.  One to one sessions with a fully qualified BACP registered counsellor are £45.00, limited number of sessions with student placement counsellors are also available at a heavily discounted rate of £25.00.<br>
<br>
Self funded sessions are 50 minutes long, we offer face to face from our head office, online or telephone sessions. Counselling session costs the charity over £50 so we always welcome any donations or contributions to help us maintain and enhance the quality of our service delivery.<br> 
<br>
To refer to our self-funded counselling service by calling 01782 914455 or email @Enquiries before making payments through this website.<br>
