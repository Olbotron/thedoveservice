<h3>SOCIAL FRIENDSHIP GROUPS - DOVE BUDDIES</h3>
We recognise that not everyone who experiences a bereavement or loss needs specialist counselling to feel like themselves again. Because of that, we offer Social Groups across North Staffordshire and Cheshire.<br>
<br>
Dove Buddies is our Social Friendship Group for adults who have experienced bereavement and who may be struggling with social connections, loneliness and isolation. The aim of Dove Buddies is to forge those connections and organise activities that will help to engage our group members, encouraging socialisation and re-engagement.<br>
<br>
We organise quizzes, talks from local groups, plus visits to local attractions and places of interest. We run Dove Buddies groups within Stoke-on-Trent, North Staffordshire and Cheshire.<br>
<br>
