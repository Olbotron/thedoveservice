<h2>NHS TALKING THERAPIES</h2>
Working in partnership with NHS Staffordshire and Stoke-on-Trent Talking Therapies, we provide free one-on-one counselling to adults (16+) affected by bereavement and loss. To access this service, you must be registered with a GP, and reside within the Staffordshire or Stoke-on-Trent area.<br>
<br>
Talking Therapies also provides therapy and support to those struggling with depression, stress, anxiety, low mood, worry, phobias, and other mental and emotional issues; and also to those adjusting to living with a long-term health condition.<br>
<br>
To refer please call 0300 3030923 or visit the Talking Therapies website<br>
