<h2>BEREAVEMENT GROUPS</h2>
<br>
Our Bereavement Group meets weekly each Wednesday at 1.30 pm at Bescura Family Hub situated at Port Vale Football Club on Hamil Road in Burslem.<br>
<br>
Facilitated by trained counsellors, our bereavement groups are therapeutic support groups in which those present are provided with the space to grieve, express their feelings and share their stories in a safe and confidential setting that is inclusive and non-judgemental.<br>
<br>
Exploring your loss as part of a bereavement group and sharing your experiences with others who are also grieving can help you find a way forward through your individual experience of bereavement.<br>
<br>
The bereavement groups are designed for individuals to attend as and when they feel it would be helpful for them. Members can attend weekly or space their attendances out. There's no requirement for all those attending to speak - It may just be helpful to be present and among others with shared experiences of bereavement.<br>
<br>
If you would like to attend a bereavement group, please register at least 24 hours before attending by registering your details below or call us on 01782 914455.<br>
