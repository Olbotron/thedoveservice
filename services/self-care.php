<h1>Self Care</h1>
<h2>WHAT IS SELF-CARE AND WHY IS IT IMPORTANT?</h2>
Have you ever listened to a safety demonstration on an aeroplane?  When the stewards demonstrate putting on the emergency oxygen masks they always say that you should fit your own mask before attempting to help anyone else.<br>
<br>
This is the principle of self-care. If you don’t look after yourself you will struggle to help others.<br>
<br>
People often confuse self-care with selfishness but the two things are very different.  Being selfish means that you lack any consideration for others and are mainly focused on your own needs/desires, often at the cost of others.<br>
<br>
But having self care is about putting your mental, emotional and physical health at the top of your priority list, and learning to be kind to yourself.<br>
<br>
As the saying goes "You can't pour from an empty cup"!<br>
<br>
If you are struggling with certain elements of self-care or would like to develop your self-care further, we hope that you will find the information and worksheets on this page useful.<br>
<br>
<h2>WHAT IS GRIEF?</h2>
<br>
THE PRINCIPLE OF SELF-CARE - "IF YOU DON'T LOOK AFTER YOURSELF YOU WILL STRUGGLE TO HELP OTHERS".
WHAT CAN I DO TO HELP MYSELF?<br>
Some important considerations include looking after:<br>
<br>
<strong>Eating</strong><br>
When we are experiencing a bereavement, or period of distress, it is often our eating habits that suffer.<br>
<br>
Take 5 minutes to enjoy a hot drink. Make sure you get your lunch break at work. If you don’t feel like eating anything try eating little and often rather than being over-faced by 3 bigger meals.<br>
<br>
<strong>Physical activity</strong><br>
It can be hard to find a balance when we are grieving.  Some of us want to do nothing and stop doing the activities and hobbies that we were engaged in before our bereavement, others perhaps need to keep very busy and may end up doing too much.<br>
<br>
It is important to be gentle with yourself when you are grieving or experiencing a period of distress.<br>
<br>
Physical exercise, done in moderation, can help us to feel better.  You might want to make small changes like taking the stairs instead of the lift, or taking a walk outside on your lunch break (if you’ve gone back to work).<br>
<br>
<strong>Sleep</strong><br>
Sleeping can become a big issue following a bereavement or during times of distress.  Very often it can become difficult to get to sleep, or you can find you wake-up in the night and struggle to get back to sleep.  In some cases it can feel as though all you want to do is sleep.  Grief, illness and stress are exhausting, so the combination of any of these things, with a disruption to our usual sleeping patterns can make us feel quite unwell.<br><br>
Sleep is important for recharging both our physical and mental health.  There are a number of things that you can try if you are having trouble sleeping, having a warm bath may help to relax you, not working on a computer/iPad or watching TV for at least 30 minutes helps your brain to switch off, and if you have thoughts going round your head try writing them on a pad at the side of your bed and leaving them until the next day.<br>
<br>
Have a look at our worksheets on relaxation and mindfulness for more tips about how to support your sleep better.<br>
<br>
<strong>Friends and Familiy</strong><br>
It can be easy to start to feel isolated and lonely after someone dies, or during times of high stress.  Our instinct may be to cut ourselves off from friends and family, perhaps feeling as though we don’t want to be a burden on them.  A lot of our clients tell us that they didn’t want to upset other people with their grief and so try to cope with it alone, or that other people don’t seem to know what to say to them.<br>
<br>
We have a lot of experience with clients who have taken the step to talk to a loved one about how they are feeling and, almost without exception, this has been a positive experience.  Friends and family want to feel as though they are doing something that is actually helping, whether that’s just by listening, making cups of tea, grabbing some shopping for you, coming over and looking after your children for a couple of hours, going to the cinema so that you can just lose yourself in a film, making you laugh, crying with you, whatever it is that you need or that they can offer can be very helpful.<br>
<br>
<strong>Unhelpful Coping Strategies</strong><br>
It can be tempting to use things that help to block out the pain of grief, but self injury, alcohol and drugs are not positive ways of coping.<br>
<br>
If you have been prescribed drugs by your GP it is important that you take those as instructed and if you have any concerns about your physical health, you should  make an appointment to see your GP.<br>
<br>
<h3>MAINTAINING BOUNDARIES</h3>
At certain times, you may need to say "no" and have boundaries as to what you will and will not be able to undertake, take time out for yourself and aim for a better work/life balance. Remember...<br>
<br>
<ul>
<li>Be aware of the possible impact on yourself when supporting other people</li>
<li>Ask for support when you need it.</li>
<li>Learn to accept encouragement and praise.</li>
<li>Be open and honest. If you don’t know, say so.</li>
</ul><br>
<br>
Remember, caring and being there are more important than "doing".<br>
<ul>
<li>Take time out to do something you enjoy</li>
<li>Consider relaxation, exercise and healthy living</li>
<li>Remember the importance of boundaries; they are there for your protection, too.</li>
<li>Keep a diary to write down or draw to record your experiences and feelings</li>
</ul>
