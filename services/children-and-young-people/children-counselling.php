<h2>ARE YOU A CHILD OR YOUNG PERSON THINKING ABOUT COUNSELLING?</h2>
Our counsellors will work creatively with you to find ways of supporting you to express your emotions and will help you to explore how you feel about what is happening in your world.<br>
<br>
If you want to spend your session chatting about what is going on for you then that’s entirely up to you, but you can also use your other skills – like drawing, painting, and writing – or you might choose to use other materials in the counselling room to help you express how you feel.  We have lots of stuff that you can use to do that, like a doll’s house, sand trays, puppets etc.  But because it’s your session, and your time, and your feelings, you are the one who decides.<br>
