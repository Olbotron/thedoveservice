<h3>PARENTS AND PROFESSIONALS</h3>
Our Grief Out Loud project offers free support to children and young people in Staffordshire, East Cheshire and The Wirral. We can provide free workshops discussing grief in an age-appropriate format and how to support yourself and others. We also offer one-to-one school drop-ins, where a member of our counselling team visits the child’s school to help them discuss their grief, as well as support groups for events when a collective grief is experienced. Any of these can then lead to six sessions of one-to-one counselling with a member of our counselling team. All these services are funded by the National Lottery and are also available to parents, carers, and professionals who are in contact with under 18s.<br>
