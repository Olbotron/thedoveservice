<h3>WONDERING WHAT COUNSELLING MIGHT BE LIKE?</h3>
It’s your choice… Because it’s your counselling, we keep the contents of your sessions confidential.  Your counsellor will look at a counselling contract with you in your first session, and will talk to you about the circumstances under which we might have to involve someone else, but outside those circumstances, it’s your choice what you tell people about your counselling.<br>
<br>
Don’t be afraid to cry, things may seem bad now, but as time goes on you will find you can cope with your grief; what you are feeling now is normal and natural. It might take a while, but things will start to feel better. Grief can feel very lonely, but remember that other people are feeling it too and you can share your feelings with them.<br>
<br>
Remember! It is okay to cry and feel sad. But it is also okay to play and have fun with your family and friends.<br>
