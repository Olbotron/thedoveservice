<h3>OTHER REFERAL ROUTES</h3>
If your GP or a school refers your child, you may find that they contact CAMHS (Child and Adolescent Mental Health Services). If there are no clear mental health symptoms, but there is a mention of the child experiencing issues relating to bereavement , loss or life-changing illness, CAMHS  will contact the referrer with our contact information.<br>
<br>
<h3>OUT OF AREA REFERALS</h3>
If the child or young person you would like to refer is outside of Staffordshire. Please contact us on 01782 914455 for more information
