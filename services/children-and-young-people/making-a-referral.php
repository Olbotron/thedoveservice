<h1>MAKING A REFERRAL</h1>
<h3>HOW DO I REFER?</h3>
Call our Head Office on 01782 914455, we can provide advice to determine if counselling is suitable and we will take some information regarding the child you would like to refer. We do require parental/carer consent to accept children referrals.<br>
<br>
We do ask that all children under the age of 14 be accompanied to their session by an appropriate adult but will be given the choice of whether or not to have that adult present in during their counselling session. The Child or Young person will be given that choice at each of their sessions, so they can always change their mind.<br> 
<br>
(NB. This process may vary slightly depending on area).<br>
