<h2>HAVE YOU CONSIDERED VOLUNTEERING?</h2>
<h3>OVERVIEW OF THE ROLE</h3>
People choose to volunteer for a variety of reasons. For some, it offers the chance to give something back to the community or make a difference to the people around them. For others, it provides an opportunity to develop new skills or build on existing experience and knowledge. Regardless of the motivation, what unites them all is that they find it both challenging and rewarding. Whilst you'll want to make a real difference when you volunteer, it's not just about what you can do for others - volunteers get a lot out of the experience too.<br>
<br>
Here are a few of the reasons people choose to volunteer; for some, it provides an opportunity to:<br>
<br>
Give something back to an organisation that has impacted on a person’s life, either directly or indirectly
Make a difference in the lives of others
Help others less fortunate or without a voice
Feel valued and part of a team
Spend quality time away from work or a busy lifestyle
Gain confidence and self-esteem<br>
<br> 
At the Dove Service, we believe that volunteering is rewarding for everyone involved. Volunteering does wonders for your mind, body and spirit providing an opportunity to meet new people, and try new things and helping you stay connected, happy and confident.<br>
