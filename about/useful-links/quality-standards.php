<h3>What is Clinical Governance?</h3>
“The framework through which organisations are accountable for continually improving the quality of their services and safeguarding high standards of care by creating an environment in which excellence in clinical care will flourish.” (Taken from a definition commonly used by the NHS). We place great importance on maintaining the quality standards of our delivery for all clients, thus making it the heart of everything we do. Our management team meet on a fortnightly basis with an External Clinical Advisor, to ensure that we are working in the best interests of our clients and counsellors at every step.<br>
