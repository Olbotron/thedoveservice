<div class="accordion-item">
<button class="accordion-title">Is Counselling confidential?</button>  
<div class="accordion-content">
    <p>      
Trust is a big part in you feeling safe to talk to your counsellor about your thoughts and feelings. Confidentiality is important in creating this trust. Your counsellor will not discuss details of your session with your family, friends, employers, etc.<br>
<br>
There are certain circumstances where there are exceptions to confidentiality. If, for example, your counsellor was concerned by the end of the session that there was a high risk that you were going to seriously harm yourself then they have a duty of care to you to ensure you are safe. It is likely that your GP may be contacted. However, your counsellor would always try to gain your consent before doing that.<br>
<br>
Other exceptions to confidentiality would be surrounding the safety of others – child protection issues, acts of terrorism, etc.
    </p>
</div>
