<button class="accordion-title">Is my grief normal?</button>
<div class="accordion-content">
    <p>
      Grief is a normal experience for most people in life.  However, even though people can have similar reactions, grief is a highly individual experience.  There is no right or wrong way to grieve and no set time scale. It is important to allow yourself time to come to terms with loss.<br>
<br>
<strong>Someone's reactions to a death can be influenced by many factors, for example:</strong>
<ul>
<li>cultural or religious traditions;</li>
<li>personal beliefs about life after death;</li>
<li>the nature of the relationship ended by death (e.g. partner, family member, or friend);</li>
<li>the cause of death;</li>
<li>the person's age at death;</li>
<li>if the death was sudden or expected;</li>
<li>thoughts about our own death.</li>
</ul>

<strong>You may experience some, or all, of the following feelings and emotions, and in no particular order:</strong>
<ul>
<li>Shock and numbness</li>
<li>Sadness</li>
<li>Guilt</li>
<li>Anger</li>
<li>Shame</li>
<li>Loneliness</li>
<li>Depression</li>
</ul>

<strong>Some people experience physical sensations when they grieve, such as:</strong>
<ul>
<li>Tiredness, sleeplessness, bad dreams</li>
<li>Loss of appetite or increased appetite</li>
<li>Being forgetful / loss of concentration</li>
<li>Difficulty breathing / choking feeling</li>
<li>Muscle tension / headaches</li>
<li>Anxiety / feeling of panic</li>
<li>Nausea</li>
<li>Dizziness / palpitations / shaking</li>
<li>Changed interest in sex</li>
</ul>
    </p>
