<div class="accordion-item">
<button class="accordion-title">When is the right time for counselling?</button>  
<div class="accordion-content">
    <p>
As a general guide, we suggest that counselling is not always helpful within three months of a bereavement.  However, we can't say exactly how much time should pass before considering if counselling will be helpful because everyone's reaction to grief and loss is different.  Giving yourself some time after a death can give you the time to deal with some of the practical issues that are associated with bereavement and some space to begin making adjustments to your life.<br>
<br>
If you are struggling to cope on a day-to-day basis, or feel stuck in your grief, you may find that counselling could be of benefit to you no matter how recent or distant your bereavement.
    </p>
