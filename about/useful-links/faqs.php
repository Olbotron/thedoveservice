<div class="accordion-item">
<button class="accordion-title">What is Counselling?</button>  
<div class="accordion-content">
    <p>
      
At difficult times in your life you can sometimes feel isolated. It could be that you feel like you have nobody to turn to who would understand. Alternatively, for whatever reason, you may not want to turn to friends and family. At times like these you may feel it could be helpful to turn to someone independent, such as a counsellor.<br>
<br>
Counselling is a form of 'talking therapy' that can be provided in many different ways. Our aim is to create a private, undisturbed and confidential environment where we hope you will quickly be able to develop a trusting working relationship with your counsellor and can safely talk about your feelings, emotions and thoughts.<br>
<br>
Counselling is not about giving advice or having a friendly chat.  Your counsellor is an impartial professional.<br>
<br>
There are many different types of Counselling, at the Dove Service the majority of our Counsellors are trained in Person-Centred Counselling which is a 'Humanistic' approach.  In essence this means that the counselling will be lead by you, as our client, to use your inner resources to understand your thoughts and feelings, whilst offering you an environment that is non-judgemental, open, honest, empathic and respectful.<br>
<br>
If you decide to come to the Dove Service for Counselling please feel free to ask your Counsellor about their training and background, different people need different things from Counselling, so it's important to us that you get what you need.
</p>
</div>
